import assert from "node:assert/strict";
import fs from "node:fs";
const read = (path) => fs.readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const pkg = JSON.parse(read("package.json"));
assert.equal(pkg.version, "1.1.0");
const app = read("src/components/app-shell.tsx");
const scroll = read("src/lib/overlay-scroll-lock.ts");
const fullscreen = read("src/lib/use-map-fullscreen.ts");
const province = read("src/components/map-stage.tsx");
const commune = read("src/components/commune-explorer.tsx");
const styles = read("src/app/globals.css");
const mapPage = read("src/app/ban-do/page.tsx");
const docs = read("docs/ROADMAP-UI-UX-V1.0.3-TO-V2.0.0.md");
for (const [name, text] of [["province", province], ["commune", commune]]) {
  assert.match(text, /useOverlayScrollLock\(detailOpen\)/, `${name} detail must lock page`);
  assert.match(text, /useOverlayScrollLock\(listOpen\)/, `${name} picker must lock page`);
  assert.match(text, /focus\(\{ preventScroll: true \}\)/, `${name} modal should avoid focus scroll jump`);
  assert.match(text, /gis-mobile-selection-bar/, `${name} details remain map-first`);
  assert.ok(!text.includes('document.body.style.overflow = "hidden"'), `${name} old competing scroll lock found`);
}
assert.match(app, /topbar-condensed/);
assert.match(app, /useOverlayScrollLock\(mobileMenuOpen\)/);
assert.match(app, /menuDialogRef/);
assert.match(fullscreen, /useOverlayScrollLock\(fullscreen\)/);
assert.match(fullscreen, /visualViewport/);
assert.match(fullscreen, /orientationchange/);
assert.match(scroll, /activeLocks\+\+/);
assert.match(scroll, /activeLocks === 0/);
assert.match(scroll, /window.scrollTo/);
assert.match(styles, /\.vw-map-page > \.page-header/);
assert.match(styles, /\.gis-map-column\.is-map-fullscreen/);
assert.match(styles, /env\(safe-area-inset-bottom/);
assert.match(styles, /env\(safe-area-inset-top/);
assert.match(styles, /\.mobile-drawer\{/);
assert.match(mapPage, /vw-map-page/);
assert.match(docs, /V2\.0\.0/);
assert.match(read("src/lib/config.ts"), /export const UX_ROADMAP/);
assert.match(read("src/app/gioi-thieu/page.tsx"), /UX_ROADMAP\.map/);
assert.match(read("public/sw.js"), /v1\.1\.0/);
console.log("PASS V1.0.3: shared iOS scroll lock; compact header; fullscreen & modal focus; responsive safe area; roadmap saved; PWA version updated.");
